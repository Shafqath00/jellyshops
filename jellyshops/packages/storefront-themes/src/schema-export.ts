import { z } from "zod";
import { BLOCK_STYLE_CONTROLS, SECTION_STYLE_CONTROLS, blockStyleSchema, isBlockStyleKey, isSectionStyleKey, listBlockDefinitions, listSectionDefinitions, sectionStyleSchema } from "@jelly/storefront-registry";
import { starterFileSchema } from "./starter-file-schema.js";
import { themeManifestSchema } from "./theme-resolver.js";

/**
 * Machine-readable descriptions of what a theme may contain, generated from the platform's own
 * schemas so they cannot drift: a JSON Schema for the manifest (editor autocompletion and CI) and a
 * catalogue of every section and block with its settings, editor controls, limits and defaults.
 * `scripts/generate-schemas.mjs` writes them to docs/schemas/; a test fails if the files are stale.
 */
function jsonSchemaOf(schema: z.ZodType): unknown {
  try { return z.toJSONSchema(schema, { unrepresentable: "any", io: "input" }); }
  catch { return null; }
}

/**
 * The schema without the properties every section (or block) shares, which are listed once under
 * `shared`. zod merges the shared and own schemas into one list of properties, so identical entries
 * are removed by name.
 */
function ownSchemaOf(schema: z.ZodType, shared: unknown): unknown {
  const full = jsonSchemaOf(schema) as { properties?: Record<string, unknown>; required?: string[]; $schema?: string } | null;
  const common = (shared as { properties?: Record<string, unknown> } | null)?.properties;
  if (!full?.properties || !common) return full;
  const own = Object.fromEntries(Object.entries(full.properties).filter(([key, value]) => JSON.stringify(value) !== JSON.stringify(common[key])));
  const required = (full.required ?? []).filter((key) => key in own);
  // The `$schema` line is the same everywhere, so it is left out of each entry.
  return { ...full, $schema: undefined, properties: own, required: required.length ? required : undefined };
}

export function buildSchemaFiles(): Record<string, string> {
  const sharedSectionSettings = jsonSchemaOf(sectionStyleSchema);
  const sharedBlockSettings = jsonSchemaOf(blockStyleSchema);
  const manifest = z.toJSONSchema(themeManifestSchema, { io: "input" });
  // Core sections only: a section a theme adds itself (limited to that theme) is described in its own theme.json.
  const sections = listSectionDefinitions().filter((definition) => !definition.themes).map((definition) => ({
    type: definition.type,
    category: definition.category,
    supportedPages: definition.supportedPages,
    allowedRegions: definition.allowedRegions,
    allowedBlockTypes: definition.allowedBlockTypes,
    minBlocks: definition.minBlocks,
    maxBlocks: definition.maxBlocks,
    defaultSettings: definition.defaultSettings,
    defaultBlocks: definition.defaultBlocks.map((block) => ({ type: block.type, settings: block.settings })),
    responsiveFields: definition.responsiveFields,
    presets: definition.presets,
    controls: definition.controls.filter((control) => !isSectionStyleKey(control.key)),
    settingsSchema: ownSchemaOf(definition.settingsSchema, sharedSectionSettings),
  }));
  const blocks = listBlockDefinitions().map((definition) => ({
    type: definition.type,
    allowedBlockTypes: definition.allowedBlockTypes,
    maxBlocks: definition.maxBlocks,
    defaultSettings: definition.defaultSettings,
    controls: definition.controls.filter((control) => !isBlockStyleKey(control.key)),
    settingsSchema: ownSchemaOf(definition.settingsSchema, sharedBlockSettings),
  }));
  const format = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;
  return {
    "theme.schema.json": format({ $comment: "Generated by scripts/generate-schemas.mjs from the platform's theme manifest schema. Do not edit.", ...manifest }),
    "starter.schema.json": format({ $comment: "Generated by scripts/generate-schemas.mjs from the starter file schema. Do not edit.", ...(z.toJSONSchema(starterFileSchema, { unrepresentable: "any", io: "input" }) as object) }),
    "sections.json": format({
      $comment: "Generated by scripts/generate-schemas.mjs from the section and block registry. Do not edit. Every section also has the `shared.sectionControls` and every styled block the `shared.blockControls`; they are listed once here.",
      shared: { sectionControls: SECTION_STYLE_CONTROLS, sectionSettingsSchema: sharedSectionSettings, blockControls: BLOCK_STYLE_CONTROLS, blockSettingsSchema: sharedBlockSettings },
      sections,
      blocks,
    }),
  };
}
