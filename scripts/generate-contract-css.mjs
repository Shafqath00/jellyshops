#!/usr/bin/env node
/**
 * Writes the Jelly Design Contract token defaults (packages/storefront-themes/src/contract-tokens.ts) into
 * jellyshops/src/app/themes/storefront-base.css, between the contract-tokens:start/end markers.
 *
 *   node scripts/generate-contract-css.mjs           rewrite the block
 *   node scripts/generate-contract-css.mjs --check   fail if the block is out of date
 *
 * Reads the built package, so run `npm run build:storefront-packages` in jellyshops/ first.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cssPath = join(root, "jellyshops/src/app/themes/storefront-base.css");
const { contractTokenCss } = await import(pathToFileURL(join(root, "jellyshops/packages/storefront-themes/dist/contract-tokens.js")).href);

const START = "/* contract-tokens:start — generated by scripts/generate-contract-css.mjs from contract-tokens.ts; do not edit by hand. */";
const END = "/* contract-tokens:end */";
const css = readFileSync(cssPath, "utf8");
const block = `${START}\n${contractTokenCss()}\n${END}`;
const start = css.indexOf(START);
const end = css.indexOf(END);
const next = start >= 0 && end > start
  ? `${css.slice(0, start)}${block}${css.slice(end + END.length)}`
  : css.replace(/^(\/\*[^]*?\*\/\n)/, `$1\n${block}\n\n`);

if (process.argv.includes("--check")) {
  if (next !== css) {
    console.error("storefront-base.css contract tokens are out of date: run node scripts/generate-contract-css.mjs");
    process.exit(1);
  }
  console.log("Contract tokens are up to date.");
} else {
  writeFileSync(cssPath, next);
  console.log(next === css ? "Contract tokens already up to date." : "Wrote contract tokens into storefront-base.css.");
}
