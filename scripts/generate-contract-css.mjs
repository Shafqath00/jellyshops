#!/usr/bin/env node
/**
 * Writes the Jelly Design Contract token defaults (packages/storefront-themes/src/contract-tokens.ts) and the text
 * role rules (textRoleCss in theme-style-settings.ts) into jellyshops/src/app/themes/storefront-base.css, between their
 * start/end markers.
 *
 *   node scripts/generate-contract-css.mjs           rewrite the blocks
 *   node scripts/generate-contract-css.mjs --check   fail if a block is out of date
 *
 * Reads the built package, so run `npm run build:storefront-packages` in jellyshops/ first.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cssPath = join(root, "jellyshops/src/app/themes/storefront-base.css");
const dist = (file) => pathToFileURL(join(root, "jellyshops/packages/storefront-themes/dist", file)).href;
const { contractTokenCss } = await import(dist("contract-tokens.js"));
const { textRoleCss } = await import(dist("theme-style-settings.js"));

const blocks = [
  {
    start: "/* contract-tokens:start — generated by scripts/generate-contract-css.mjs from contract-tokens.ts; do not edit by hand. */",
    end: "/* contract-tokens:end */",
    css: contractTokenCss(),
    // First time: after the file's opening comment.
    place: (css, block) => css.replace(/^(\/\*[^]*?\*\/\n)/, `$1\n${block}\n\n`),
  },
  {
    start: "/* text-roles:start — Theme settings > Text role: … (template plan T7); generated by scripts/generate-contract-css.mjs from textRoleCss() in theme-style-settings.ts; do not edit by hand. */",
    end: "/* text-roles:end */",
    css: textRoleCss(),
    place: (css, block) => `${css.trimEnd()}\n\n${block}\n`,
  },
];

const original = readFileSync(cssPath, "utf8");
let next = original;
for (const { start: START, end: END, css, place } of blocks) {
  const block = `${START}\n${css}\n${END}`;
  const start = next.indexOf(START);
  const end = next.indexOf(END);
  next = start >= 0 && end > start ? `${next.slice(0, start)}${block}${next.slice(end + END.length)}` : place(next, block);
}

if (process.argv.includes("--check")) {
  if (next !== original) {
    console.error("storefront-base.css generated blocks are out of date: run node scripts/generate-contract-css.mjs");
    process.exit(1);
  }
  console.log("Contract tokens and text roles are up to date.");
} else {
  writeFileSync(cssPath, next);
  console.log(next === original ? "Generated blocks already up to date." : "Wrote contract tokens and text roles into storefront-base.css.");
}
