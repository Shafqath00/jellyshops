// Turns a folder theme's theme.css into the app stylesheet (scoped to the theme) and copies its assets to public/.
//   node scripts/generate-theme-assets.mjs jelly-halo
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { scopeCustomCss } from "../jellyshops/packages/storefront-schema/dist/index.js";

const id = process.argv[2];
if (!/^[a-z0-9-]+$/.test(id ?? "")) throw new Error("Usage: node scripts/generate-theme-assets.mjs <theme-id>");
const source = new URL(`../jellyshops/packages/storefront-themes/src/themes/${id}/`, import.meta.url);
const css = readFileSync(new URL("theme.css", source), "utf8");
const scoped = scopeCustomCss(css, `[data-jelly-theme="${id}"]`, css.length);
if (!scoped) throw new Error(`${id} stylesheet is invalid`);
writeFileSync(new URL(`../jellyshops/src/app/themes/${id}.css`, import.meta.url), `/* Generated by scripts/generate-theme-assets.mjs ${id}. */\n${scoped}\n`);
const publicAssets = new URL(`../jellyshops/public/themes/${id}/`, import.meta.url);
mkdirSync(publicAssets, { recursive: true });
cpSync(new URL("assets/", source), publicAssets, { recursive: true });
console.log(`Generated ${id} styles and public assets`);
