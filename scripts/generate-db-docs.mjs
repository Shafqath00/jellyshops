// Generates docs/architecture/database-schema.md by reading the schema of the
// database that backend/.env points at (read-only queries only) and mapping
// each table to the backend files that reference it.
// Run from the repo root: node scripts/generate-db-docs.mjs
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const pg = createRequire(path.join(root, "backend", "package.json"))("pg");
const envText = fs.readFileSync(path.join(root, "backend", ".env"), "utf8");
const env = Object.fromEntries(
  envText.split(/\r?\n/).filter((l) => l.includes("=") && !l.startsWith("#")).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).replace(/^"|"$/g, "")]),
);
const client = new pg.Client({
  connectionString: env.SUPABASE_DATABASE_URL,
  ssl: env.SUPABASE_DATABASE_CA_FILE ? { ca: fs.readFileSync(env.SUPABASE_DATABASE_CA_FILE, "utf8") } : { rejectUnauthorized: false },
});
await client.connect();
const q = async (sql) => (await client.query(sql)).rows;

const tables = await q(`select c.relname as name, c.relrowsecurity as rls from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='r' order by 1`);
const columns = await q(`select table_name t, column_name c, data_type || coalesce('('||character_maximum_length||')','') as type, is_nullable n, column_default d from information_schema.columns where table_schema='public' order by table_name, ordinal_position`);
const constraints = await q(`select conrelid::regclass::text t, conname, contype, pg_get_constraintdef(oid) def from pg_constraint where connamespace='public'::regnamespace order by 1, 3, 2`);
const indexes = await q(`select tablename t, indexname i, indexdef def from pg_indexes where schemaname='public' order by 1, 2`);
const triggers = await q(`select c.relname t, tg.tgname name from pg_trigger tg join pg_class c on c.oid=tg.tgrelid where c.relnamespace='public'::regnamespace and not tg.tgisinternal order by 1, 2`);
const applied = await q(`select version, name from supabase_migrations.schema_migrations order by 1`);
await client.end();

const srcRoot = path.join(root, "backend", "src");
const sources = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const f = path.join(d, e.name);
    if (e.isDirectory()) walk(f);
    else if (e.name.endsWith(".ts") && !e.name.endsWith(".test.ts")) sources.push([path.relative(root, f).split(path.sep).join("/"), fs.readFileSync(f, "utf8")]);
  }
})(srcRoot);

const q2 = (s) => s.replace(/\|/g, "\\|");
const unq = (t) => t.replace(/^public\./, "").replace(/"/g, "");
let out = `# Database schema\n\n> Generated by \`scripts/generate-db-docs.mjs\` from the live schema of the database referenced by \`backend/.env\` (the staging Supabase project) plus a scan of \`backend/src\`. Do not edit by hand; re-run the script.\n\n`;
out += `${tables.length} tables in the \`public\` schema. Row-level security is enabled on tables marked **RLS**; browser-facing Supabase roles have no direct access to server-owned tables, only the backend runtime role does (see \`backend/sql/security\` and the isolation migrations).\n\n`;
out += `## Applied migrations (supabase_migrations.schema_migrations)\n\n${applied.map((m) => `- \`${m.version}\`${m.name ? ` ${m.name}` : ""}`).join("\n")}\n\nMigration SQL lives in \`backend/sql/migrations\` and \`backend/supabase/migrations\`.\n\n`;
out += `## Relationship overview\n\nForeign keys between tables (child → parent):\n\n\`\`\`mermaid\nerDiagram\n`;
const fkLines = new Set();
for (const c of constraints.filter((x) => x.contype === "f")) {
  const m = c.def.match(/REFERENCES ("?[\w]+"?)\(/);
  if (m) fkLines.add(`  ${unq(m[1])} ||--o{ ${unq(c.t)} : has`);
}
out += [...fkLines].sort().join("\n") + "\n```\n\n";
out += `## Tables\n\n`;
for (const t of tables) {
  const refs = sources.filter(([, text]) => new RegExp(`"${t.name}"`).test(text)).map(([f]) => f);
  out += `### \`${t.name}\`${t.rls ? " — RLS" : ""}\n\n`;
  out += `| Column | Type | Null | Default |\n| --- | --- | --- | --- |\n`;
  for (const c of columns.filter((x) => x.t === t.name)) out += `| \`${c.c}\` | ${c.type} | ${c.n === "YES" ? "yes" : "no"} | ${c.d ? `\`${q2(c.d)}\`` : ""} |\n`;
  const own = constraints.filter((x) => unq(x.t) === t.name);
  if (own.length) {
    out += `\nConstraints:\n\n`;
    const label = { p: "PRIMARY KEY", f: "FOREIGN KEY", u: "UNIQUE", c: "CHECK", x: "EXCLUDE" };
    for (const c of own) out += `- ${label[c.contype] ?? c.contype}: \`${c.conname}\` — \`${c.def.length > 300 ? c.def.slice(0, 297) + "..." : c.def}\`\n`;
  }
  const idx = indexes.filter((x) => x.t === t.name && !own.some((c) => c.conname === x.i));
  if (idx.length) {
    out += `\nIndexes:\n\n`;
    for (const i of idx) out += `- \`${i.i}\` — \`${i.def.replace(/^CREATE (UNIQUE )?INDEX \S+ ON public\./, (m, u) => (u ? "UNIQUE " : "")).replace(/\s+/g, " ")}\`\n`;
  }
  const trg = triggers.filter((x) => x.t === t.name);
  if (trg.length) out += `\nTriggers: ${trg.map((x) => `\`${x.name}\``).join(", ")}\n`;
  out += `\nReferenced by: ${refs.length ? refs.map((r) => `\`${r}\``).join(", ") : "no backend source file (migration/seed only)"}\n\n`;
}
fs.mkdirSync(path.join(root, "docs", "architecture"), { recursive: true });
fs.writeFileSync(path.join(root, "docs", "architecture", "database-schema.md"), out);
console.log("tables", tables.length);
