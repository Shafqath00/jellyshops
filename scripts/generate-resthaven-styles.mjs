import { readFileSync, writeFileSync } from 'node:fs';
import { scopeCustomCss } from '../jellyshops/packages/storefront-schema/dist/index.js';
const source = new URL('../jellyshops/packages/storefront-themes/src/themes/jelly-resthaven/theme.css', import.meta.url);
const target = new URL('../jellyshops/src/app/themes/jelly-resthaven.css', import.meta.url);
const css = readFileSync(source, 'utf8');
const scoped = scopeCustomCss(css, '[data-jelly-theme="jelly-resthaven"]', css.length);
if (!scoped) throw new Error('Resthaven stylesheet is invalid');
writeFileSync(target, '/* Generated by scripts/generate-resthaven-styles.mjs. */\n' + scoped + '\n');
