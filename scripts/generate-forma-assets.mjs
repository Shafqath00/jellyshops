import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { scopeCustomCss } from "../jellyshops/packages/storefront-schema/dist/index.js";

const source = new URL("../jellyshops/packages/storefront-themes/src/themes/jelly-forma/", import.meta.url);
const css = readFileSync(new URL("theme.css", source), "utf8");
const scoped = scopeCustomCss(css, '[data-jelly-theme="jelly-forma"]', css.length);
if (!scoped) throw new Error("Forma stylesheet is invalid");
writeFileSync(new URL("../jellyshops/src/app/themes/jelly-forma.css", import.meta.url), `/* Generated by scripts/generate-forma-assets.mjs. */\n${scoped}\n`);
const publicAssets = new URL("../jellyshops/public/themes/jelly-forma/", import.meta.url);
mkdirSync(publicAssets, { recursive: true });
cpSync(new URL("assets/", source), publicAssets, { recursive: true });
console.log("Generated Forma styles and public assets");
