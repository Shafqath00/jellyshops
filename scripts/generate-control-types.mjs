#!/usr/bin/env node
/**
 * Writes jellyshops/packages/storefront-registry/src/control-types.generated.ts: for every built-in section and block,
 * the settings whose control type changes how a custom-field value is shown (image, link, rich text, product,
 * collection). Store pages read this table instead of loading the section definitions (see runtime-lookup.ts).
 *
 *   node scripts/generate-control-types.mjs           rewrite the file
 *   node scripts/generate-control-types.mjs --check   fail if it is out of date
 *
 * Reads the built package, so run `npm run build:storefront-packages` in jellyshops/ first (and again after writing).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = join(root, "jellyshops", "packages", "storefront-registry");
const { listSectionDefinitions, listBlockDefinitions } = await import(pathToFileURL(join(pkg, "dist", "index.js")).href);
const SHAPED = new Set(["image", "link", "rich-text", "product", "collection"]);
const table = (definitions) => Object.fromEntries(definitions
  .map((definition) => [definition.type, Object.fromEntries(definition.controls.filter((control) => SHAPED.has(control.type)).map((control) => [control.key, control.type]))])
  .filter(([, types]) => Object.keys(types).length)
  .sort(([a], [b]) => a.localeCompare(b)));
const json = (value) => JSON.stringify(value, null, 2);
const text = `// Generated by scripts/generate-control-types.mjs from the built-in section and block definitions. Do not edit.\nexport const SECTION_CONTROL_TYPES: Record<string, Record<string, string>> = ${json(table(listSectionDefinitions()))};\nexport const BLOCK_CONTROL_TYPES: Record<string, Record<string, string>> = ${json(table(listBlockDefinitions()))};\n`;
const target = join(pkg, "src", "control-types.generated.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== text) { console.error("control-types.generated.ts is out of date: run node scripts/generate-control-types.mjs"); process.exit(1); }
  console.log("control-types.generated.ts is up to date");
} else { writeFileSync(target, text); console.log("Wrote control-types.generated.ts"); }
