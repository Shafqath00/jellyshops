#!/usr/bin/env node
/**
 * Lists the theme folders in jellyshops/packages/storefront-themes/src/themes/ so the platform finds
 * them without anyone editing a registry file.
 *
 *   node scripts/generate-theme-index.mjs           write src/themes/index.generated.ts
 *   node scripts/generate-theme-index.mjs --check   fail if the file is out of date
 *
 * A theme folder holds `theme.json` (required, the manifest) and may hold `starter.json` (the
 * templates and shared sections a new store starts with) and `layout-history.json` (earlier starter
 * layouts, so stores built from them can be upgraded). Themes that need code (custom header,
 * footer or section markup) are still registered by hand in theme-registry.ts; a folder whose id
 * is already registered there is left alone. Everything else becomes a declarative theme.
 *
 * Two files: index.generated.ts holds the manifests (and whether a theme's starter brings its own header and footer),
 * which every store page needs; starters.generated.ts holds the starters and layout histories, which only installing,
 * upgrading and previewing need, so shoppers never download them (Phase 6 speed work).
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const themesDirectory = join(root, "jellyshops/packages/storefront-themes/src/themes");

function themeFolders(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(directory, entry.name, "theme.json")))
    .map((entry) => entry.name)
    .sort();
}

/** True when a starter has its own header and footer (the store then draws its chrome itself). */
function ownChrome(directory, folder) {
  const file = join(directory, folder, "starter.json");
  if (!existsSync(file)) return false;
  const globals = Object.values(JSON.parse(readFileSync(file, "utf8")).globalSections ?? {});
  return globals.some((section) => section?.type === "header") && globals.some((section) => section?.type === "footer");
}

export function buildThemeIndex(directory = themesDirectory) {
  const folders = themeFolders(directory);
  const imports = [];
  const entries = [];
  folders.forEach((folder, index) => {
    imports.push(`import manifest${index} from "./${folder}/theme.json" with { type: "json" };`);
    entries.push(`  { manifest: manifest${index}${ownChrome(directory, folder) ? ", ownChrome: true" : ""} },`);
  });
  return `// Generated by scripts/generate-theme-index.mjs from the folders next to this file. Do not edit.
${imports.join("\n")}
import type { DiscoveredTheme } from "../types.js";

export const discoveredThemes: DiscoveredTheme[] = [
${entries.join("\n")}
] as DiscoveredTheme[];
`;
}

/** Starters and layout histories by theme id (installing, upgrading and previewing only). */
export function buildStarterIndex(directory = themesDirectory) {
  const imports = [];
  const entries = [];
  themeFolders(directory).forEach((folder, index) => {
    const id = JSON.parse(readFileSync(join(directory, folder, "theme.json"), "utf8")).id ?? folder;
    const parts = [];
    if (existsSync(join(directory, folder, "starter.json"))) {
      imports.push(`import starter${index} from "./${folder}/starter.json" with { type: "json" };`);
      parts.push(`starter: starter${index}`);
    }
    if (existsSync(join(directory, folder, "layout-history.json"))) {
      imports.push(`import layoutHistory${index} from "./${folder}/layout-history.json" with { type: "json" };`);
      parts.push(`layoutHistory: layoutHistory${index}`);
    }
    if (parts.length) entries.push(`  ${JSON.stringify(id)}: { ${parts.join(", ")} },`);
  });
  return `// Generated by scripts/generate-theme-index.mjs from the folders next to this file. Do not edit.
${imports.join("\n")}
import type { DiscoveredTheme } from "../types.js";

export const discoveredStarters: Record<string, Pick<DiscoveredTheme, "starter" | "layoutHistory">> = {
${entries.join("\n")}
} as Record<string, Pick<DiscoveredTheme, "starter" | "layoutHistory">>;
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dirFlag = process.argv.indexOf("--dir");
  if (dirFlag !== -1) {
    // Print the index for another folder (used by the tests); nothing is written.
    process.stdout.write(buildThemeIndex(resolve(process.argv[dirFlag + 1])) + buildStarterIndex(resolve(process.argv[dirFlag + 1])));
    process.exit(0);
  }
  const files = [["index.generated.ts", buildThemeIndex()], ["starters.generated.ts", buildStarterIndex()]];
  for (const [name, content] of files) {
    const target = join(themesDirectory, name);
    if (process.argv.includes("--check")) {
      if (!existsSync(target) || readFileSync(target, "utf8") !== content) {
        console.error(`src/themes/${name} is out of date. Run: node scripts/generate-theme-index.mjs`);
        process.exit(1);
      }
    } else {
      writeFileSync(target, content);
      console.log(`wrote jellyshops/packages/storefront-themes/src/themes/${name}`);
    }
  }
}
