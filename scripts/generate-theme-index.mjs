#!/usr/bin/env node
/**
 * Lists the theme folders in jellyshops/packages/storefront-themes/src/themes/ so the platform finds
 * them without anyone editing a registry file.
 *
 *   node scripts/generate-theme-index.mjs           write src/themes/index.generated.ts
 *   node scripts/generate-theme-index.mjs --check   fail if the file is out of date
 *
 * A theme folder holds `theme.json` (required, the manifest) and may hold `starter.json` (the
 * templates and shared sections a new store starts with). Themes that need code (custom header,
 * footer or section markup) are still registered by hand in theme-registry.ts; a folder whose id
 * is already registered there is left alone. Everything else becomes a declarative theme.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const themesDirectory = join(root, "jellyshops/packages/storefront-themes/src/themes");

export function buildThemeIndex(directory = themesDirectory) {
  const folders = readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(directory, entry.name, "theme.json")))
    .map((entry) => entry.name)
    .sort();
  const imports = [];
  const entries = [];
  folders.forEach((folder, index) => {
    imports.push(`import manifest${index} from "./${folder}/theme.json" with { type: "json" };`);
    if (existsSync(join(directory, folder, "starter.json"))) {
      imports.push(`import starter${index} from "./${folder}/starter.json" with { type: "json" };`);
      entries.push(`  { manifest: manifest${index}, starter: starter${index} },`);
    } else entries.push(`  { manifest: manifest${index} },`);
  });
  return `// Generated by scripts/generate-theme-index.mjs from the folders next to this file. Do not edit.
${imports.join("\n")}
import type { DiscoveredTheme } from "../types.js";

export const discoveredThemes: DiscoveredTheme[] = [
${entries.join("\n")}
] as DiscoveredTheme[];
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dirFlag = process.argv.indexOf("--dir");
  if (dirFlag !== -1) {
    // Print the index for another folder (used by the tests); nothing is written.
    process.stdout.write(buildThemeIndex(resolve(process.argv[dirFlag + 1])));
    process.exit(0);
  }
  const target = join(themesDirectory, "index.generated.ts");
  const content = buildThemeIndex();
  if (process.argv.includes("--check")) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== content) {
      console.error("src/themes/index.generated.ts is out of date. Run: node scripts/generate-theme-index.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(target, content);
    console.log("wrote jellyshops/packages/storefront-themes/src/themes/index.generated.ts");
  }
}
