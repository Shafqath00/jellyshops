-- Shop web addresses nobody may choose (system names, brands, offensive words). The list in
-- jellyshops/packages/storefront-schema/src/store-address.ts is the source; a backend test keeps this seed equal to it.
-- Nothing reads this table yet: the address-change function (tenancy plan step 8) will check it inside the database.
-- See docs/plans/2026-11-22-subdomain-tenancy-plan.md section 7.
CREATE TABLE IF NOT EXISTS "ReservedSlug" (
  "slug" TEXT NOT NULL,
  "reason" TEXT NOT NULL,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT "ReservedSlug_pkey" PRIMARY KEY ("slug"),
  CONSTRAINT "ReservedSlug_reason_check" CHECK ("reason" IN ('system', 'brand', 'profanity', 'lookalike')),
  CONSTRAINT "ReservedSlug_slug_check" CHECK ("slug" = lower("slug") AND char_length("slug") BETWEEN 1 AND 63)
);

ALTER TABLE public."ReservedSlug" ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public."ReservedSlug" FROM PUBLIC;
DO $isolate$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN REVOKE ALL ON public."ReservedSlug" FROM anon; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN REVOKE ALL ON public."ReservedSlug" FROM authenticated; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'jelly_backend') THEN
    GRANT SELECT, INSERT, UPDATE, DELETE ON public."ReservedSlug" TO jelly_backend;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'ReservedSlug' AND policyname = 'backend_access') THEN
      CREATE POLICY backend_access ON public."ReservedSlug" TO jelly_backend USING (true) WITH CHECK (true);
    END IF;
  END IF;
END
$isolate$;

